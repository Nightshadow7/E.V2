import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { createServer } from 'vite';
import { createElement, act } from 'react';

import { instalarMocks } from './mock-supabase.mjs';
const dom = new JSDOM('<!doctype html><div id="root"></div>', { url: 'http://localhost/pqrs' });
for (const key of ['window','document','localStorage','HTMLElement','HTMLDialogElement','Event','MouseEvent','HTMLInputElement','HTMLTextAreaElement']) globalThis[key] = dom.window[key];
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
dom.window.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
dom.window.HTMLDialogElement.prototype.close=function(){this.open=false;};
globalThis.alert=()=>{};
const server=await createServer({server:{middlewareMode:true},appType:'custom'});
const {createRoot}=await import('react-dom/client');
let clienteSupabase;
const root=createRoot(document.getElementById('root'));
const render=async element=>{await act(async()=>{root.render(element);});};
const click=async element=>{assert.ok(element,'Control no encontrado');await act(async()=>element.click());};
const fill=async (element,value)=>{ const prototype=element instanceof HTMLTextAreaElement ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype; await act(async()=>{Object.getOwnPropertyDescriptor(prototype,'value').set.call(element,value);element.dispatchEvent(new Event('input',{bubbles:true}));}); };
const submit=async form=>{await act(async()=>form.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})));};
const button=text=>[...document.querySelectorAll('button')].find(b=>b.textContent.includes(text));
const text=()=>document.body.textContent;
try {
 const {supabase}=await server.ssrLoadModule('/src/supabaseClient.js');
 clienteSupabase=supabase;
 const mock=instalarMocks(supabase);
 const {default:App}=await server.ssrLoadModule('/src/App.jsx');
 await render(createElement(App));
 for(const tipo of ['Petición','Queja','Reclamo','Felicitación','Desvinculación']) assert.ok(document.querySelector(`section[aria-label="Solicitudes de ${tipo}"]`),tipo);
 await click(button('Ver detalles #pqr-2'));
 assert.ok(document.querySelector('dialog[open]'));
 assert.ok(text().includes('Descripción de Queja'));
 await click(button('Guardar seguimiento'));
 assert.ok(mock.calls.some(c=>c.table==='pqrs' && c.action==='update'));
 assert.equal(document.querySelector('dialog'),null);
 const {Trazabilidad}=await server.ssrLoadModule('/src/pages/Trazabilidad.jsx');
 const before=mock.calls.length;
 await render(createElement(Trazabilidad,{user:{...mock.user,rol:'Comercial'}}));
 assert.ok(text().includes('Acceso restringido'));
 assert.equal(mock.calls.slice(before).filter(c=>c.table==='auditoria_eventos').length,0);
 await render(createElement(Trazabilidad,{user:{...mock.user,rol:'Lider'}}));
 assert.ok(text().includes('Operador de prueba'));
 await click(button('Ver cambios'));
 assert.ok(text().includes('Anterior') && text().includes('Actualizado'));
 const {FormularioDetallePQRS}=await server.ssrLoadModule('/src/components/pqrs/FormularioDetallePQRS.jsx');
 let form={tipo_solicitud:'Petición',asunto:'',descripcion:'',urgencia:'media',datos_extra:{}};
 for(const tipo of ['Queja','Reclamo','Felicitación','Desvinculación']) {
   await render(createElement(FormularioDetallePQRS,{formData:form,setFormData:fn=>{form=typeof fn==='function'?fn(form):fn;},isClienteSeleccionado:true}));
   await click(document.querySelector(`input[name="tipo_solicitud"][value="${tipo}"]`));
   assert.equal(form.tipo_solicitud,tipo);
 }
 const {VariablesSistema}=await server.ssrLoadModule('/src/components/settings/VariablesSistema.jsx');
 await render(createElement(VariablesSistema,{user:mock.user}));
 await click(button('Guardar configuración'));
 assert.ok(mock.calls.some(c=>c.table==='configuracion_sistema' && c.action==='update'));
 await render(createElement(VariablesSistema,{user:{...mock.user,rol:'Lider'}}));
 assert.ok(document.querySelector('fieldset').disabled);
 const {Login}=await server.ssrLoadModule('/src/pages/Login.jsx');
 mock.authError={message:'Credenciales inválidas'};
 let loggedIn=false;
 await render(createElement(Login,{onLogin:()=>{loggedIn=true;}}));
 await act(async()=>{document.querySelector('form').dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));});
 assert.ok(mock.calls.some(c=>c.action==='login'));
 assert.equal(loggedIn,false);
 assert.ok(text().includes('Correo o contraseña incorrectos'));
 const {MiCuenta}=await server.ssrLoadModule('/src/components/settings/MiCuenta.jsx');
 await render(createElement(MiCuenta,{user:{...mock.user,rol:'Comercial'}}));
 assert.ok(button('Cambiar correo') && button('Actualizar contraseña'));
 mock.authError=null;
 await fill(document.querySelector('input[type="email"]'),'nuevo@example.test');
 await submit(document.querySelectorAll('form')[1]);
 assert.ok(mock.calls.some(c=>c.action==='updateUser' && c.values.email==='nuevo@example.test'));
 assert.ok(text().includes('Cambio solicitado'));
 const passwordInputs=document.querySelectorAll('input[type="password"]');
 await fill(passwordInputs[0],'test-current-password');
 await fill(passwordInputs[1],'test-new-password');
 await fill(passwordInputs[2],'test-new-password');
 await submit(document.querySelectorAll('form')[2]);
 assert.ok(mock.calls.some(c=>c.action==='updateUser' && c.values.password==='test-new-password' && c.values.current_password==='test-current-password'));
 assert.ok(text().includes('Contraseña actualizada'));
 // Una copia de rol manipulada en el navegador no debe dar acceso ni consultar la auditoría.
 mock.user.rol='Comercial'; mock.session=true;
 localStorage.setItem('ecoUser',JSON.stringify({...mock.user,rol:'Administrador'}));
 window.history.replaceState({},'', '/trazabilidad');
 await render(createElement(App,{key:'commercial'}));
 assert.ok(text().includes('Acceso restringido'));
 assert.ok(![...document.querySelectorAll('a')].some(a=>a.textContent==='Trazabilidad'));
 console.log('OK interacción: categorías, detalle y guardado, cambio de tipo, trazabilidad por rol, configuración protegida, credenciales rechazadas y cuenta Comercial.');
} finally {await act(async()=>root.unmount());await clienteSupabase?.auth.stopAutoRefresh(); clienteSupabase?.auth.broadcastChannel?.close(); await server.close();dom.window.close();}
